#!/usr/bin/env python3
"""Read the Rust-validated canonical catalog snapshot shipped with one payload.

Watcher never discovers callable skills by scanning a repository or importing an
installer. The snapshot is generated by ATM after validating payload content.
"""
from __future__ import annotations

import json
import os
import re
from dataclasses import dataclass
from pathlib import Path, PurePosixPath
from typing import Any

REPOSITORY_ROOT_ENV = "ATM_HARNESS_ROOT"
CATALOG_FILENAME = "canonical-catalog.json"
CATALOG_SCHEMA_VERSION = 1
MAX_CATALOG_BYTES = 8 * 1024 * 1024
NAME = re.compile(r"[A-Za-z0-9][A-Za-z0-9._-]*\Z")


@dataclass(frozen=True)
class RepositorySource:
    root: Path
    catalog_snapshot: Path
    watcher_runtime: Path
    watcher_cli: Path


@dataclass(frozen=True)
class SkillSource:
    id: str
    plugin: str
    name: str
    path: Path
    directory_name: str
    aliases: tuple[str, ...]


@dataclass(frozen=True)
class SkillCatalog:
    sources: tuple[SkillSource, ...]
    source_identity: str
    attribution_overlays: tuple[dict[str, Any], ...]


def expand_path(raw: str | Path) -> Path:
    if isinstance(raw, Path):
        return raw.expanduser()
    return Path(os.path.expandvars(str(raw))).expanduser()


def resolve_repository_path(path: Path, *, root: Path, label: str, kind: str) -> Path:
    """Reject links and paths escaping the explicit immutable payload root."""
    try:
        relative = path.relative_to(root)
    except ValueError as exc:
        raise SystemExit(f"{label} escapes explicit payload root: {path}") from exc
    current = root
    for component in relative.parts:
        if component in {"", ".", ".."}:
            raise SystemExit(f"invalid {label} path: {path}")
        current = current / component
        try:
            if current.is_symlink() or (hasattr(current, "is_junction") and current.is_junction()):
                raise SystemExit(f"{label} contains a link: {path}")
        except OSError as exc:
            raise SystemExit(f"cannot inspect {label}: {path}: {exc}") from exc
    try:
        resolved = path.resolve(strict=True)
        resolved.relative_to(root)
    except (OSError, ValueError) as exc:
        raise SystemExit(f"cannot resolve {label} inside explicit payload root: {path}: {exc}") from exc
    if kind == "file" and not resolved.is_file():
        raise SystemExit(f"{label} is not a file: {resolved}")
    if kind == "directory" and not resolved.is_dir():
        raise SystemExit(f"{label} is not a directory: {resolved}")
    if kind not in {"file", "directory"}:
        raise ValueError(f"unsupported path kind: {kind}")
    return resolved


def resolve_repository_source(repo_root: str | Path | None = None) -> RepositorySource:
    raw = repo_root if repo_root is not None else os.environ.get(REPOSITORY_ROOT_ENV)
    if raw is None or not str(raw).strip():
        raise SystemExit(f"ATM payload root is required; pass --repo-root or set {REPOSITORY_ROOT_ENV}")
    candidate = expand_path(raw)
    if not candidate.is_absolute():
        raise SystemExit(f"ATM payload root must be absolute: {candidate}")
    try:
        root = candidate.resolve(strict=True)
    except OSError as exc:
        raise SystemExit(f"cannot resolve ATM payload root {candidate}: {exc}") from exc
    if not root.is_dir():
        raise SystemExit(f"ATM payload root is not a directory: {root}")
    snapshot = resolve_repository_path(root / CATALOG_FILENAME, root=root, label="canonical catalog snapshot", kind="file")
    runtime = resolve_repository_path(root / "runtimes" / "watcher", root=root, label="Watcher runtime", kind="directory")
    cli = resolve_repository_path(runtime / "scripts" / "watcher", root=root, label="Watcher CLI", kind="file")
    return RepositorySource(root, snapshot, runtime, cli)


def _portable_path(value: Any, *, label: str) -> str:
    if not isinstance(value, str) or not value or "\\" in value or ":" in value:
        raise SystemExit(f"invalid catalog {label}")
    path = PurePosixPath(value)
    if path.is_absolute() or any(part in {"", ".", ".."} for part in value.split("/")):
        raise SystemExit(f"invalid catalog {label}")
    return value


def _name(value: Any, *, label: str) -> str:
    if not isinstance(value, str) or not NAME.fullmatch(value):
        raise SystemExit(f"invalid catalog {label}")
    return value


def _identity(value: Any) -> str:
    if not isinstance(value, str) or len(value.split(":")) != 2:
        raise SystemExit("invalid catalog stable skill identity")
    for part in value.split(":"):
        _name(part, label="stable skill identity")
    return value


def _unique_object(pairs: list[tuple[str, Any]]) -> dict[str, Any]:
    result: dict[str, Any] = {}
    for key, value in pairs:
        if key in result:
            raise ValueError(f"duplicate JSON key: {key}")
        result[key] = value
    return result


def load_repository_skill_catalog(source: RepositorySource) -> SkillCatalog:
    """Consume the versioned snapshot; there is deliberately no discovery fallback."""
    try:
        with source.catalog_snapshot.open("rb") as handle:
            raw = handle.read(MAX_CATALOG_BYTES + 1)
        if len(raw) > MAX_CATALOG_BYTES:
            raise ValueError("catalog exceeds the size limit")
        data = json.loads(raw, object_pairs_hook=_unique_object)
    except (OSError, UnicodeError, ValueError) as exc:
        raise SystemExit(f"invalid canonical catalog snapshot {source.catalog_snapshot}: {exc}") from exc
    if not isinstance(data, dict) or type(data.get("schemaVersion")) is not int or data.get("schemaVersion") != CATALOG_SCHEMA_VERSION or data.get("product") != "atm-harness-catalog":
        raise SystemExit("unsupported canonical catalog snapshot schema or product")
    identity = data.get("sourceIdentity")
    if not isinstance(identity, str) or not re.fullmatch(r"[0-9a-f]{64}", identity):
        raise SystemExit("invalid canonical catalog sourceIdentity")
    entries = data.get("skills")
    overlays = data.get("attributionOverlays")
    if not isinstance(entries, list) or not isinstance(overlays, list):
        raise SystemExit("canonical catalog skills and attributionOverlays must be lists")
    sources: list[SkillSource] = []
    ids: set[str] = set()
    names: set[str] = set()
    paths: set[str] = set()
    for entry in entries:
        if not isinstance(entry, dict):
            raise SystemExit("invalid canonical catalog skill entry")
        stable_id = _identity(entry.get("id"))
        plugin = _name(entry.get("plugin"), label="plugin")
        name = _name(entry.get("name"), label="name")
        dirname = _name(entry.get("directoryName"), label="directoryName")
        relative = _portable_path(entry.get("path"), label="path")
        if relative != f"plugins/{plugin}/skills/{dirname}":
            raise SystemExit("catalog skill path does not match its package identity")
        aliases = entry.get("aliases")
        if not isinstance(aliases, list) or any(not isinstance(alias, str) or not alias for alias in aliases):
            raise SystemExit("invalid canonical catalog aliases")
        if stable_id in ids or name in names or relative.casefold() in paths:
            raise SystemExit("duplicate canonical catalog skill identity, name, or path")
        ids.add(stable_id)
        names.add(name)
        paths.add(relative.casefold())
        sources.append(SkillSource(stable_id, plugin, name, source.root / relative, dirname, tuple(aliases)))
    overlay_plugins: set[str] = set()
    for overlay in overlays:
        if not isinstance(overlay, dict) or not isinstance(overlay.get("data"), dict):
            raise SystemExit("invalid canonical attribution overlay")
        plugin = _name(overlay.get("plugin"), label="overlay plugin")
        path = _portable_path(overlay.get("path"), label="overlay path")
        if path != f"plugins/{plugin}/.codex-plugin/skill-watcher.json" or plugin in overlay_plugins:
            raise SystemExit("duplicate or mismatched canonical attribution overlay")
        overlay_plugins.add(plugin)
    return SkillCatalog(tuple(sources), identity, tuple(overlays))
